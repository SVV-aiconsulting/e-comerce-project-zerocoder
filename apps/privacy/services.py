@dataclass(frozen=True)
class CurrentDocuments:
    policy: PersonalDataDocumentVersion
    consent: PersonalDataDocumentVersion


class ConsentService:
    @staticmethod
    def current_documents() -> CurrentDocuments:
        today = timezone.localdate()
        initial_effective_from = date(2026, 9, 5)
        defaults = (
            (PersonalDataDocumentType.POLICY, "1.0", POLICY_TEXT, "/privacy-policy/v/1.0/"),
            (PersonalDataDocumentType.CONSENT, "1.0", CONSENT_TEXT, "/personal-data-consent/v/1.0/"),
            (PersonalDataDocumentType.POLICY, "1.1", POLICY_TEXT_V1_1, "/privacy-policy/v/1.1/"),
            (PersonalDataDocumentType.CONSENT, "1.1", CONSENT_TEXT_V1_1, "/personal-data-consent/v/1.1/"),
        )
        documents = {}
        for document_type, version, content, public_path in defaults:
            document, _ = PersonalDataDocumentVersion.objects.get_or_create(
                document_type=document_type, version=version,
                defaults={
                    "effective_from": date(2026, 9, 7) if version == "1.1" else initial_effective_from,
                    "content": content,
                    "public_path": public_path,
                },
            )
            documents[document_type] = (
                PersonalDataDocumentVersion.objects.filter(
                    document_type=document_type,
                    effective_from__lte=today,
                )
                .order_by("-effective_from", "-id")
                .first()
                or document
            )
        return CurrentDocuments(policy=documents[PersonalDataDocumentType.POLICY], consent=documents[PersonalDataDocumentType.CONSENT])

    @classmethod
    def has_current_consent(cls, *, channel, identity_value) -> bool:
        current = cls.current_documents()
        event = PersonalDataConsentEvent.objects.filter(channel=channel, identity_value=identity_value, purpose=PURPOSE).order_by("-occurred_at", "-id").first()
        return bool(event and event.status == ConsentStatus.GRANTED and event.consent_document_id == current.consent.id and event.policy_document_id == current.policy.id)

    @classmethod
    @transaction.atomic
    def record(cls, *, channel, identity_type, identity_value, source, status, expression_method, customer=None, evidence=None, identification_level=None):
        current = cls.current_documents()
        identification_level = identification_level or (
            IdentityLevel.WEBSITE_SESSION
            if channel == "website"
            else IdentityLevel.PLATFORM_ACCOUNT
        )
        previous = PersonalDataConsentEvent.objects.filter(channel=channel, identity_value=identity_value, purpose=PURPOSE).order_by("-occurred_at", "-id").first()
        if (
            status == ConsentStatus.GRANTED
            and previous is not None
            and previous.status == ConsentStatus.GRANTED
            and (
                previous.consent_document_id != current.consent.id
                or previous.policy_document_id != current.policy.id
            )
        ):
            previous = PersonalDataConsentEvent.objects.create(
                customer=previous.customer,
                identity_type=previous.identity_type,
                identity_value=previous.identity_value,
                identification_level=previous.identification_level,
                channel=previous.channel,
                source="document_version_superseded",
                purpose=previous.purpose,
                status=ConsentStatus.SUPERSEDED,
                occurred_at=timezone.now(),
                consent_document=previous.consent_document,
                policy_document=previous.policy_document,
                expression_method=previous.expression_method,
                evidence={"reason": "new_document_version"},
                previous_event=previous,
            )
        event = PersonalDataConsentEvent.objects.create(
            customer=customer, identity_type=identity_type, identity_value=identity_value,
            identification_level=identification_level,
            channel=channel, source=source, purpose=PURPOSE, status=status,
            occurred_at=timezone.now(), consent_document=current.consent,
            policy_document=current.policy, expression_method=expression_method,
            evidence=evidence or {}, previous_event=previous,
        )
        if customer is not None:
            type(customer).objects.filter(pk=customer.pk).update(
                personal_data_consent_registry_key=event.public_id,
                personal_data_consent=status == ConsentStatus.GRANTED,
            )
        return event

    @classmethod
    def withdraw(cls, *, channel, identity_type, identity_value, source, expression_method, customer=None):
        event = cls.record(
            channel=channel,
            identity_type=identity_type,
            identity_value=identity_value,
            source=source,
            status=ConsentStatus.WITHDRAWN,
            expression_method=expression_method,
            customer=customer,
            evidence={
                "processing_restricted": True,
                "erasure_review_required": True,
            },
        )
        if customer is not None:
            customer.personal_data_consent = False
            customer.save(update_fields=["personal_data_consent", "updated_at"])
        return event
